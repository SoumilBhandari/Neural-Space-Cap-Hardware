"""Export a fitted head into OpenSCAD, so the printed frame fits the person.

The CAD needs to know the shape of the head it is wrapping. Rather than
re-implement ellipse arc-length in OpenSCAD — which has no while loop and no
root finder, and where a forward reference silently evaluates to undef — this
module writes the geometry out as plain data: the head's semi-axes, the band
paths as polylines, and each electrode mount as a point plus the two rotations
that stand a cylinder up along the surface normal.

The .scad files then only have to sweep and subtract, which is what OpenSCAD
is actually good at.
"""

from __future__ import annotations

import math
from pathlib import Path

import numpy as np

from .head import Head
from .ten_twenty import (
    CORONAL,
    LATERAL_LEFT,
    MIDLINE,
    MONTAGE_V1,
    PHASE_1,
    Site,
    lateral_loop,
    temple_site,
)

# Points per band. A band is swept as a hull of spheres at consecutive points,
# so between them its surface is a straight chord that sags inward. Denser
# sampling shrinks that sag quadratically.
BAND_STEPS = 96

# Extra standoff on top of the liner gap.
#
# Placing a centreline exactly on the surface it is cut against leaves no room
# for the chord sag above: the cut is tangent to the centreline, so any sag at
# all means the subtraction bites into the band. Measured sag was up to
# 1.23 mm on the sagittal arch, which necked the bands visibly — a pinch next
# to a socket that looks like a divot taken out of the part.
#
# The band still has a flat inner face conforming to the head; it just sits
# this much prouder of it.
CHORD_MARGIN = 1.5


def write_head_params(head: Head, sites: dict[str, Site], path: str | Path) -> Path:
    """Write the head geometry and band paths as an OpenSCAD include file."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    sagittal = head.sagittal_arc()
    coronal = head.coronal_arc()
    _, loop_len = lateral_loop(head, sites)
    loop = head.circumference_arc(float(sites["Fpz"].xyz_mm[2] + sites["Oz"].xyz_mm[2]) / 2.0)

    # A closed ring plus two arches. Separate front and rear bands would each
    # be cantilevered off a single joint at the midline and would flex; a
    # closed loop braced by two arches is stiff, and is how EEG caps are built.
    bands = {
        # The ring, carrying Fpz, the temples, T7, T8, O1, Oz and O2.
        "lateral": _sample(loop, 0.0, 1.0, closed=True),
        # Over the top, front to back.
        "sagittal": _sample(sagittal, MIDLINE["Fpz"], MIDLINE["Oz"]),
        # Ear to ear over the vertex, carrying C3, Cz and C4. The fraction is
        # CORONAL's, not LATERAL_LEFT's: T7 is 10% along the coronal arc but
        # 25% around the lateral loop, and using the loop figure here stops the
        # arch halfway down the side of the head, short of the ring it is
        # supposed to brace.
        "coronal": _sample(coronal, CORONAL["T7"], 1.0 - CORONAL["T7"]),
        # Two more arches, because F3, F4, P3 and P4 sit on neither the ring
        # nor either existing arch. These are the standard frontal and parietal
        # chains, and both land on the ring at their ends, so they brace it
        # rather than hanging off it.
        "frontal": _surface_path(head, [sites[n].xyz_mm for n in ("F7", "F3", "Fz", "F4", "F8")]),
        "parietal": _surface_path(head, [sites[n].xyz_mm for n in ("P7", "P3", "Pz", "P4", "P8")]),
    }

    lines = [
        "// Generated by nsc_fit — do not edit.",
        f"// Fitted from circumference {head.measurements.circumference_mm:.0f} mm, "
        f"nasion-inion {head.measurements.nasion_inion_mm:.0f} mm, "
        f"ear-to-ear {head.measurements.preauricular_mm:.0f} mm.",
        "",
        f"head_axes = [{head.a_mm:.3f}, {head.b_mm:.3f}, {head.c_mm:.3f}];",
        f"lateral_loop_len = {loop_len:.2f};",
        "",
    ]
    for name, points in bands.items():
        lines.append(f"band_{name} = {_vector_list(points)};")
    lines.append("")

    # Electrode mounts, as one list so adding or dropping a site needs no edit
    # to the CAD: [name, position, rotation, phase_one].
    # The rotation aligns +Z with the outward surface normal, so every socket
    # stands straight out of the skull instead of being eyeballed.
    lines.append("// [name, position, [rot_x, rot_y, rot_z], phase_one]")
    entries = []
    for name in MONTAGE_V1:
        point = sites[name].xyz_mm
        elevation, azimuth = _normal_rotation(head, point)
        flag = 1 if name in PHASE_1 else 0
        entries.append(
            f'["{name}", {_vector(point)}, [0, {elevation:.3f}, {azimuth:.3f}], {flag}]'
        )
    lines.append("mounts = [\n    " + ",\n    ".join(entries) + "\n];")
    lines.append("")

    # The PPG sensor seat on the temple.
    temple = temple_site(head, sites)
    elevation, azimuth = _normal_rotation(head, temple.xyz_mm)
    lines.append(
        f"ppg_mount = [{_vector(temple.xyz_mm)}, [0, {elevation:.3f}, {azimuth:.3f}]];"
    )

    # The pod sits behind and below Oz, on the flat of the occiput.
    pod_point = loop.at_fraction(0.5)
    elevation, azimuth = _normal_rotation(head, pod_point)
    lines.append("")
    lines.append(f"pod_anchor = [{_vector(pod_point)}, [0, {elevation:.3f}, {azimuth:.3f}]];")

    path.write_text("\n".join(lines) + "\n")
    return path


def _sample(arc, start_fraction: float, end_fraction: float, closed: bool = False) -> np.ndarray:
    """Sample a band path evenly along an arc, by arc length not by angle.

    ``closed`` repeats the first point at the end so a swept ring joins up
    instead of leaving a gap the width of one step.
    """
    fractions = np.linspace(start_fraction, end_fraction, BAND_STEPS)
    points = np.array([arc.at_fraction(min(f, 1.0)) for f in fractions])
    if closed:
        points[-1] = points[0]
    return points


def _surface_path(head: Head, control_points: list, steps: int = 14) -> np.ndarray:
    """A smooth path across the head through a list of points on its surface.

    The frontal and parietal chains are not planar ellipses — F3 and P3 are
    defined as lying between two other sites, so the chain through them is a
    curve with no closed form. Interpolating in the plane and projecting
    afterwards would sag the path inside the skull between control points.

    Instead the points are mapped to a unit sphere, where the shortest path
    between two of them is a great-circle arc with an exact formula, and then
    mapped back. Every sampled point lands on the head surface by construction.
    """
    axes = np.array([head.a_mm, head.b_mm, head.c_mm])
    units = [p / axes for p in control_points]
    units = [u / np.linalg.norm(u) for u in units]

    out: list[np.ndarray] = []
    for i in range(len(units) - 1):
        a, b = units[i], units[i + 1]
        omega = math.acos(float(np.clip(np.dot(a, b), -1.0, 1.0)))
        last = i == len(units) - 2
        for t in np.linspace(0.0, 1.0, steps, endpoint=last):
            if omega < 1e-9:
                point = a
            else:
                point = (math.sin((1 - t) * omega) * a + math.sin(t * omega) * b) / math.sin(omega)
            out.append(point * axes)
    return np.array(out)


def _normal_rotation(head: Head, point: np.ndarray) -> tuple[float, float]:
    """Rotations in degrees that align +Z with the outward normal at ``point``.

    The gradient of x²/a² + y²/b² + z²/c² gives the normal directly. OpenSCAD's
    rotate([0, elevation, azimuth]) then maps +Z onto it.
    """
    axes = np.array([head.a_mm, head.b_mm, head.c_mm])
    normal = point / (axes**2)
    normal = normal / np.linalg.norm(normal)
    elevation = math.degrees(math.acos(float(np.clip(normal[2], -1.0, 1.0))))
    azimuth = math.degrees(math.atan2(float(normal[1]), float(normal[0])))
    return elevation, azimuth


def _vector(point) -> str:
    return "[" + ", ".join(f"{v:.3f}" for v in point) + "]"


def _vector_list(points) -> str:
    return "[" + ", ".join(_vector(p) for p in points) + "]"


def write_scan_params(
    scan,
    head: Head,
    sites: dict[str, Site],
    path: str | Path,
    stl_name: str = "scan_head.stl",
    standoff_mm: float = 4.0,
) -> Path:
    """Write band paths and mounts lying on her scanned surface.

    The 10-20 layout still comes from the fitted ellipsoid, because the
    standard is defined by arc percentages between bony landmarks and nothing
    on this scan marks them. What changes is where those positions land: each
    site's *direction* from the head centre is taken from the ellipsoid, and
    its *position* is read off her scanned surface along that direction.

    So the montage keeps its standard geometry — O1 is still where O1 belongs
    relative to the rest — while the frame that carries it follows her actual
    contour, including the parting where her hair is thicker on one side.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    # Both models are measured from a centre the same distance below the
    # crown, so a direction means the same thing in each.
    ellipsoid_centre = np.array([0.0, 0.0, head.c_mm - 110.0])

    def onto_scan(point: np.ndarray) -> np.ndarray:
        """Her surface in this direction, standing off by the liner gap.

        The bands have to clear the inflated surface they are hollowed
        against, not sit on it. A band swept at 11 mm about a centreline lying
        on the surface, minus a 4 mm inflation, keeps 1.5 mm of material — and
        the scan is bumpier than that, so the bands come out chewed into
        fragments. Offsetting the centreline by the same gap gives the band
        its full radius back.
        """
        direction = np.asarray(point) - ellipsoid_centre
        direction = direction / np.linalg.norm(direction)
        surface = scan.surface_towards(direction)
        return surface + direction * (standoff_mm + CHORD_MARGIN) - scan.centre

    bands = {
        "lateral": _project(_sample(_loop_of(head, sites), 0.0, 1.0, closed=True), onto_scan),
        "sagittal": _project(
            _sample(head.sagittal_arc(), MIDLINE["Fpz"], MIDLINE["Oz"]), onto_scan
        ),
        "coronal": _project(
            _sample(head.coronal_arc(), CORONAL["T7"], 1.0 - CORONAL["T7"]), onto_scan
        ),
        "frontal": _project(
            _surface_path(head, [sites[n].xyz_mm for n in ("F7", "F3", "Fz", "F4", "F8")]),
            onto_scan,
        ),
        "parietal": _project(
            _surface_path(head, [sites[n].xyz_mm for n in ("P7", "P3", "Pz", "P4", "P8")]),
            onto_scan,
        ),
    }

    # The frame trims off anything hanging below its own lowest band. On the
    # ellipsoid that height was a constant above the landmark plane, but scan
    # coordinates are measured from a centre inside the skull, so a fixed
    # number there slices straight through the middle of the head and cuts the
    # ring into loose pieces.
    lowest = min(float(p[2]) for band in bands.values() for p in band)

    lines = [
        "// Generated by nsc_fit from a LiDAR scan — do not edit.",
        "// Band paths and mounts lie on the scanned surface, not on an ellipsoid.",
        "",
        f'scan_stl = "{stl_name}";',
        f"scan_trim_z = {lowest - 14.0:.3f};",
        f"head_axes = [{head.a_mm:.3f}, {head.b_mm:.3f}, {head.c_mm:.3f}];",
        "",
    ]
    for name, points in bands.items():
        lines.append(f"band_{name} = {_vector_list(points)};")
    lines.append("")

    # Sacrificial print feet. The frame is a swept tube on a curved path, so
    # nothing on it is flat: laid ring-down it touches the plate at a single
    # tangent point with 0.0 mm2 of first-layer area, which no brim can rescue
    # because there is nothing for the brim to attach to. Feet give it real
    # footprint, and snap off at a deliberately thin neck.
    lines.append("// Sacrificial feet: contact points chosen round the ring.")
    lines.append(f"feet = {_vector_list(_foot_points(bands['lateral']))};")
    lines.append("")

    lines.append("// [name, position, [rot_x, rot_y, rot_z], phase_one]")
    entries = []
    for name in MONTAGE_V1:
        point = onto_scan(sites[name].xyz_mm)
        elevation, azimuth = _scan_normal_rotation(scan, point)
        entries.append(
            f'["{name}", {_vector(point)}, [0, {elevation:.3f}, {azimuth:.3f}], '
            f"{1 if name in PHASE_1 else 0}]"
        )
    lines.append("mounts = [\n    " + ",\n    ".join(entries) + "\n];")
    lines.append("")

    temple = onto_scan(temple_site(head, sites).xyz_mm)
    elevation, azimuth = _scan_normal_rotation(scan, temple)
    lines.append(f"ppg_mount = [{_vector(temple)}, [0, {elevation:.3f}, {azimuth:.3f}]];")

    pod = onto_scan(_loop_of(head, sites).at_fraction(0.5))
    elevation, azimuth = _scan_normal_rotation(scan, pod)
    lines.append(f"pod_anchor = [{_vector(pod)}, [0, {elevation:.3f}, {azimuth:.3f}]];")

    path.write_text("\n".join(lines) + "\n")
    return path


def _loop_of(head: Head, sites: dict[str, Site]):
    z_ref, _ = lateral_loop(head, sites)
    return head.circumference_arc(z_ref)


def _project(points: np.ndarray, onto) -> np.ndarray:
    return np.array([onto(p) for p in points])


def _scan_normal_rotation(scan, point: np.ndarray) -> tuple[float, float]:
    """Rotations aligning +Z with the scan's outward normal at ``point``.

    Estimated by finite differences across the height field rather than from
    an analytic gradient — the scanned surface has no closed form. Smoothed
    beforehand, so the normals are stable enough to stand a socket on.
    """
    base = np.asarray(point, dtype=float)
    d = base / np.linalg.norm(base)
    theta = math.acos(float(np.clip(d[2], -1, 1)))
    phi = math.atan2(d[1], d[0])

    step = math.radians(4.0)
    p_theta = scan.surface(min(theta + step, math.radians(77.0)), phi) - scan.surface(
        max(theta - step, 0.0), phi
    )
    p_phi = scan.surface(theta, phi + step) - scan.surface(theta, phi - step)
    normal = np.cross(p_phi, p_theta)

    # At the crown theta is zero, every azimuth meets, and the phi derivative
    # vanishes — the cross product is the zero vector and normalising it gives
    # NaN. OpenSCAD does not complain about rotate([0, nan, nan]); it silently
    # produces garbage, and Cz is exactly where four bands meet, so the garbage
    # splits the frame into pieces. Fall back to the radial direction, which at
    # the pole is the correct normal anyway.
    length = float(np.linalg.norm(normal))
    if not np.isfinite(length) or length < 1e-9:
        normal = d
    else:
        normal = normal / length
        if np.dot(normal, d) < 0:
            normal = -normal

    elevation = math.degrees(math.acos(float(np.clip(normal[2], -1.0, 1.0))))
    azimuth = math.degrees(math.atan2(float(normal[1]), float(normal[0])))
    return elevation, azimuth


# Feet closer together than this are redundant; further apart and the part
# rocks between them.
FOOT_SPACING_MM = 45.0
MAX_FEET = 8


def _foot_points(ring: np.ndarray) -> list:
    """Low points around the ring to stand the print on.

    Picked lowest-first and thinned by spacing, so the feet land where the
    part already hangs closest to the plate and are spread far enough apart to
    stop it rocking.
    """
    order = np.argsort(ring[:, 2])
    chosen: list[np.ndarray] = []
    for index in order:
        point = ring[index]
        if all(np.linalg.norm(point[:2] - other[:2]) >= FOOT_SPACING_MM for other in chosen):
            chosen.append(point)
        if len(chosen) >= MAX_FEET:
            break
    return chosen
